/** Hints for the page the person is on: the tabs of its section, one by one (nothing when the page has no tabs). */
export function pageSteps(path: string, tabs: Array<{ path: string; label: string }>): TourStep[] {
  const group = groupOfPath(path);
  if (!group || tabs.length < 2) return [];
  const steps: TourStep[] = [
    {
      target: null,
      title: `Раздел «${group.label}»`,
      text: `В этом разделе несколько вкладок (они вверху страницы). Сейчас покажу каждую.`,
    },
  ];
  for (const tab of tabs) {
    steps.push({
      target: `.section-tabs__link[href="${tab.path}"]`,
      title: tab.label,
      text: TAB_TEXT[tab.path] ?? '',
    });
  }
  return steps;
}

export const PAGE_TEXT: Record<string, string> = TAB_TEXT;
