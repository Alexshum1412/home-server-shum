/** The entry whose question pattern matches the text, if any. */
export function matchFaq(text: string): Faq | undefined {
  const lower = text.toLowerCase().replace(/ё/g, 'е');
  return FAQ.find((entry) => entry.match.test(lower));
}

export const faqById = (id: string): Faq | undefined => FAQ.find((entry) => entry.id === id);
