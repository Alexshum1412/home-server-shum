import { expect, test } from '@playwright/test';
import { signIn } from './helpers.ts';
const OUT = 'C:/Users/PC/AppData/Local/Temp/claude/C--/e1ff23e8-997a-47ac-8eee-0220fded2b6b/scratchpad/shots';
test('first sign-in, tour, olivia, profile', async ({ page }) => {
  test.setTimeout(150_000);
  await page.setViewportSize({ width: 1280, height: 800 });
  await signIn(page, 'callee', '/', { firstTime: true });
  await expect(page.getByRole('dialog', { name: 'Давайте познакомимся' })).toBeVisible();
  await page.screenshot({ path: OUT + '/1-onboarding.png' });
  await page.getByRole('button', { name: 'Позже' }).click();
  await expect(page.getByRole('dialog', { name: 'Добро пожаловать!' })).toBeVisible();
  await page.screenshot({ path: OUT + '/2-tour-1.png' });
  await page.getByRole('button', { name: 'Дальше' }).click();
  await page.getByRole('button', { name: 'Дальше' }).click();
  await page.screenshot({ path: OUT + '/3-tour-3.png' });
  for (let i = 0; i < 10; i += 1) await page.getByRole('button', { name: 'Дальше' }).click();
  await page.screenshot({ path: OUT + '/4-tour-last.png' });
  await page.getByRole('button', { name: 'Готово' }).click();
  await page.goto('/olivia');
  await page.getByLabel('Сообщение Оливии').fill('Сколько места на диске?');
  await page.getByRole('button', { name: 'Отправить' }).click();
  await expect(page.locator('.olivia-turn').filter({ hasText: /Диск/ }).last()).toBeVisible({ timeout: 20000 });
  await page.getByLabel('Сообщение Оливии').fill('Посоветуй рецепт борща');
  await page.getByRole('button', { name: 'Отправить' }).click();
  await page.waitForTimeout(3000);
  await page.screenshot({ path: OUT + '/5-olivia.png' });
  await page.goto('/account');
  await page.waitForLoadState('networkidle');
  await page.screenshot({ path: OUT + '/6-account.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/cinema');
  await page.waitForLoadState('networkidle');
  await page.getByRole('button', { name: 'Подсказки: как пользоваться' }).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: OUT + '/7-phone-page-tour.png' });
});